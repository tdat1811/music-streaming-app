// Kiểm thử đơn vị: AI Fan Insight ở app – giai đoạn 6 (sheet UT39). Giai đoạn 6b: lượt chuyển sang AI Assistant (UT41).
import { fallbackText, footerText, formatMoney, formatUsd, paymentBadge, paymentLabel } from '../insights';

describe('UT39 – giá', () => {
  it.each([
    ['UTCID01', 3, '$3'],
    ['UTCID02', 9.99, '$9.99'],
    ['UTCID03', 19.98, '$19.98'],
    ['UTCID04', 0, '$0'],
  ])('%s: formatUsd(%d) → %s', (_ma, vao, ra) => {
    expect(formatUsd(vao)).toBe(ra);
  });
});

describe('UT39 – tiền VNĐ của ví (cách A: mọi khoản mua trừ vào ví)', () => {
  it.each([
    ['UTCID05', 59000, 'VND', '59.000đ'],
    ['UTCID06', 75000, undefined, '75.000đ'],
    ['UTCID07', 1250000, 'VND', '1.250.000đ'],
    ['UTCID08', 0, 'VND', '0đ'],
    ['UTCID09', 3, 'USD', '$3'],
  ])('%s: formatMoney(%d, %s) → %s', (_ma, so, tien, ra) => {
    expect(formatMoney(so, tien as string | undefined)).toBe(ra);
  });
});

describe('UT39 – chữ hiển thị', () => {
  it('UTCID10: lý do dùng bản cơ bản', () => {
    expect(fallbackText('no_key')).toMatch(/isn't set up/);
    expect(fallbackText('quota')).toMatch(/free limit/);
    expect(fallbackText('ai_error')).toMatch(/isn't available/);
  });

  it('UTCID11: dòng chân trang theo nguồn', () => {
    expect(footerText('gemini', '2h ago', 86)).toBe('Generated by Gemini · 2h ago · based on 86 comments and your stats.');
    expect(footerText('basic', 'just now', 1)).toBe('Basic summary · just now · based on 1 comment and your stats.');
  });

  it('UTCID12: nhãn giao dịch', () => {
    expect(paymentLabel('vip').title).toBe('VIP Premium');
    expect(paymentLabel('ai_insight').title).toBe('AI Fan Insight');
    expect(paymentLabel('ai_messages').title).toBe('AI Assistant');
    expect(paymentLabel('deposit').title).toBe('Top up via MoMo');
    expect(paymentLabel('withdraw').title).toBe('Withdraw to MoMo');
    expect(paymentLabel('xyz').title).toBe('Payment');
  });

  it('UTCID13: nhãn trạng thái giao dịch AI (gói 20 tin, lượt Insight cũ)', () => {
    expect(paymentBadge({ type: 'ai_messages', credits: 20, creditsUsed: 5 })).toEqual({ label: '5/20 used', tone: 'ok' });
    expect(paymentBadge({ type: 'ai_messages', credits: 20, creditsUsed: 20 })).toEqual({ label: 'All used', tone: 'grey' });
    expect(paymentBadge({ type: 'ai_insight', credits: 20, creditsUsed: 0 })).toEqual({ label: '0/20 used', tone: 'ok' });
    expect(paymentBadge({ type: 'ai_insight', credits: 0, used: true })).toEqual({ label: 'Used', tone: 'grey' });
    expect(paymentBadge({ type: 'vip' })).toBeNull();
  });
});
