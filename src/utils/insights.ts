// "$3" / "$9.99" / "$19.98"
export const formatUsd = (amount: number) => {
  const n = Math.round((Number(amount) || 0) * 100) / 100;
  return `$${Number.isInteger(n) ? n : n.toFixed(2)}`;
};

// Vì sao đang xem bản tóm tắt cơ bản
export const fallbackText = (reason?: string | null) => {
  switch (reason) {
    case 'no_key':
      return "The AI isn't set up on this server yet, so this summary was made with simple word counts.";
    case 'quota':
      return "The AI's free limit was reached, so this summary was made with simple word counts. Try again later.";
    case 'blocked':
    case 'invalid_output':
      return "The AI couldn't write a proper report this time, so this summary was made with simple word counts.";
    default:
      return "The AI service isn't available right now, so this summary was made with simple word counts. Try again later.";
  }
};

// Dòng chân trang: "Generated by Gemini · 2h ago · based on 86 comments and your stats."
export const footerText = (source: string, when: string, commentCount: number) =>
  `${source === 'gemini' ? 'Generated by Gemini' : 'Basic summary'} · ${when} · based on ${commentCount} comment${commentCount === 1 ? '' : 's'} and your stats.`;

export const PAYMENT_LABELS: Record<string, { title: string; icon: 'diamond-outline' | 'sparkles-outline' | 'card-outline' }> = {
  vip: { title: 'VIP Premium', icon: 'diamond-outline' },
  ai_insight: { title: 'AI Fan Insight', icon: 'sparkles-outline' },
  ai_messages: { title: 'AI Assistant', icon: 'sparkles-outline' },
};
export const paymentLabel = (type: string) => PAYMENT_LABELS[type] || { title: 'Payment', icon: 'card-outline' as const };

// Nhãn trạng thái của giao dịch AI: gói tin nhắn "5/20 used" / "All used"; lượt Insight cũ "Used" / "Available"
export const paymentBadge = (p: { type: string; credits?: number; creditsUsed?: number; used?: boolean | null }) => {
  if ((p.credits || 0) > 0) {
    const used = p.creditsUsed || 0;
    return used >= (p.credits || 0) ? { label: 'All used', tone: 'grey' as const } : { label: `${used}/${p.credits} used`, tone: 'ok' as const };
  }
  if (p.type === 'ai_insight') return p.used ? { label: 'Used', tone: 'grey' as const } : { label: 'Available', tone: 'ok' as const };
  return null;
};
