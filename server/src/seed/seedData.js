async function seedDatabase() {
  try {
    await connectDB();

    console.log('🧹 Đang dọn dẹp dữ liệu cũ trong MongoDB Atlas...');
    await Promise.all([
      User.deleteMany(),
      Song.deleteMany(),
      Album.deleteMany(),
      Artist.deleteMany(),
      Playlist.deleteMany(),
      Chart.deleteMany(),
      FeedPost.deleteMany(),
      Comment.deleteMany(),
    ]);

    console.log('🌱 Đang chèn 52 bài hát, 12 albums, 12 artists, 8 charts...');

    // Hash mật khẩu của tất cả user mẫu bằng bcrypt trước khi lưu vào DB
    const SALT_ROUNDS = 10;
    const usersWithHashedPasswords = await Promise.all(
      users.map(async (user) => ({
        ...user,
        password: await bcrypt.hash(user.password, SALT_ROUNDS),
      }))
    );
    console.log('🔒 Đã hash tất cả mật khẩu bằng bcrypt (salt rounds: ' + SALT_ROUNDS + ')');

    await Promise.all([
      User.insertMany(usersWithHashedPasswords),
      Song.insertMany(songs),
      Album.insertMany(albums),
      Artist.insertMany(artists),
      Playlist.insertMany(playlists),
      Chart.insertMany(charts),
      FeedPost.insertMany(feedPosts),
      Comment.insertMany(comments),
    ]);

    console.log('========================================================');
    console.log('🎉 NẠP DỮ LIỆU THÀNH CÔNG VÀO MONGODB ATLAS!');
    console.log(`✅ ${songs.length} Bài hát (Songs) đa dạng kèm ảnh chất lượng cao`);
    console.log(`✅ ${albums.length} Album thịnh hành & nổi bật`);
    console.log(`✅ ${artists.length} Nghệ sĩ quốc tế & Việt Nam (đủ ảnh + bio)`);
    console.log(`✅ ${charts.length} Bảng xếp hạng (Charts Top 50 các nước)`);
    console.log(`✅ ${playlists.length} Playlists theo chủ đề (Chill, Gym, Study...)`);
    console.log(`✅ ${feedPosts.length} Bài viết Feed & Bình luận`);
    console.log('========================================================');

    process.exit(0);
  } catch (error) {
    console.error('❌ Lỗi khi nạp dữ liệu:', error);
    process.exit(1);
  }
}

seedDatabase();
